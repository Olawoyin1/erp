export function getCertificationStats(certifications = mockCertifications) {
  const total = certifications.length;
  const valid = certifications.filter((c) => c.status === 'Valid').length;
  const expiringSoon = certifications.filter((c) => c.status === 'Expiring Soon').length;
  const expired = certifications.filter((c) => c.status === 'Expired' || c.status === 'Pending Renewal').length;
  const complianceRate = total > 0 ? Math.round((valid / total) * 100) : 0;

  return { total, valid, expiringSoon, expired, complianceRate };
}
