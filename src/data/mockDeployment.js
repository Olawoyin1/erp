// Stats
export function getDeploymentStats(deployments) {
  return {
    total: deployments.length,
    active: deployments.filter(d => d.status === 'Active').length,
    pending: deployments.filter(d => d.status === 'Pending').length,
    utilisationRate: Math.round((deployments.filter(d => d.status === 'Active').length / deployments.length) * 100),
  };
}
